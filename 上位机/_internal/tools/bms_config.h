/* ---- R0 学习 (电流阶跃事件触发) ----
 * 状态机: 静置 --|I|>SOH_I_ON_MA--> 带载 --|I|<SOH_I_OFF_MA--> 断电首帧
 *         -> 次帧确认 -> R0 = (V_断电首帧 - V_带载末N帧均值) / I_带载均值
 * 滞回 (ON > OFF) 是为了让"带载段"有明确边界, 不会在门限附近反复进出。 */
#define SOH_I_ON_MA            500      /* 进入带载段的电流上门限 (mA) */
#define SOH_I_OFF_MA           200      /* 退出带载段的电流下门限 (mA) */
/* 带载段最短时长 (ms), 太短的段丢弃 —— 滤接触弹跳 / 电流计校准尖峰。
 * 注意: 实际判定用的是帧数 × BMS_UPDATE_PERIOD_MS, 改周期会自动跟随。 */
#define SOH_MIN_PULSE_MS       5000u
/* 带载末 N 帧电压平均, 作为"带载稳态电压" (N=5 即 1s @200ms)。
 * 取大 -> 包络更稳但更容易把电流下降沿的电压回跳算进去 (R0 偏低);
 * 取小 -> 更贴近阶跃瞬间, 但受单帧噪声影响大。换周期时按 ~1s 换算。 */
#define SOH_R0_TAIL_N          5
/* R0 遗忘因子下限 (样本多了以后的跟踪速度)。老化是慢变量, 快收敛比快跟踪重要。 */
#define SOH_R0_ALPHA           0.20f
/* 自适应遗忘因子分母偏置: alpha_eff = max(SOH_R0_ALPHA, 1/(n + N0))。
 * N0 越大, 前几个样本收敛越慢 (越保守); N0=2 时 n=0 -> 1/2, n=1 -> 1/3 ... */
#define SOH_R0_ALPHA_N0        2
/* 前 SOH_R0_MIN_SAMPLE 个样本的单次限幅比例 (±本值)。
 * 防单帧离谱值把某格表带跑; 样本够了就放开 (lim = 1.0)。 */
#define SOH_R0_LIMIT_RATIO     0.20f
/* 该格样本数达此值后才放开上面的限幅 */
#define SOH_R0_MIN_SAMPLE      3
/* 单次 R0 测量的合理区间 (mΩ), 越界丢弃 —— R0 对温度/荷电态敏感,
 * 但物理上 18650 不可能超出这个范围, 越界基本是采样/换算出错。
 * (与 [6] 的 SOC_R0_TABLE_* 分工不同: 这两个判"单次测量", 那组判"写表值") */
#define SOH_R0_LO_MOHM         20
#define SOH_R0_HI_MOHM         200
/* 只接受该温度窗口内的 R0 样本 (°C) —— R0 对温度很敏感,
 * 低温下内阻成倍上升, 混进来会把标定表带歪。窗口外丢弃。 */
#define SOH_TEMP_LO_C          15
#define SOH_TEMP_HI_C          35
/* 内阻翻倍视为寿命终点 (SOH_R = 0 的锚点)。
 * SOH_R = (RATIO - R0_avg/R0_fresh) / (RATIO - 1) × 100。
 * 改小 -> SOH_R 对轻微老化更敏感 (但也更容易受测量噪声影响)。 */
#define SOH_R_EOL_RATIO        2.0f

/* ---- Q 学习 (静置 OCV 锚点法) ----
 * 维护 SOC 最高/最低两个锚点, 放电后两端差值达到下面两个门槛才学一次:
 *   ΔSOC >= SOH_Q_MIN_DSOC_01 且 ΔQ >= SOH_Q_MIN_DQ_MAH
 * 门槛越松 -> 学得越快, 但 ΔSOC 太小时 Q_est 的相对误差会放大
 *           (sigma_Q(%) = SOH_Q_SIG_K / ΔSOC(%)); ΔSOC 小于 10% 时
 *           sigma_Q 超过 12.6%, 等于把系统偏差"学实", 不如不学。
 * 门槛越紧 -> 学得准, 但名义 10% 的放电循环可能永远够不到 15%。 */
#define SOH_Q_MIN_DSOC_01      1500     /* 触发学习的最小 ΔSOC (0.01% 单位, 1500 = 15%) */
#define SOH_Q_MIN_DQ_MAH       200      /* 触发学习的最小 ΔQ (mAh) */

/* ---- Q 融合: 标量卡尔曼滤波 ----
 * 状态 Q 随机游走; 量测 Q_est 方差 R = sigma^2; 正向新息把 R 放大
 * SOH_Q_KF_RUP 倍 -> SOH 上升被自然压住, 不需要死区/阻尼/限幅三个手调常数。
 * 选它不是因为"更准"(和死区方案各有胜负), 而是 sigma 估错时不崩:
 *   死区方案 k = sigma_assumed/sigma_true >= 2 时直接冻结 (波动->0);
 *   卡尔曼在 k=4 时仍在跟踪, 且稳态偏差几乎与 k 无关 (可一次性标定掉)。
 * 参数扫描 (40 次 x 2500 组, 跨度 30~80% 随机):
 *   上跳 0.23%  下跳 1.01%  稳态波动 0.71%  稳态偏差 -1.60%  老化滞后 +0.72%
 * 单次测量的相对 sigma: sigma_Q(%) = SOH_Q_SIG_K / ΔSOC(%)
 *   —— 从锚点对的 Q_est 散布估得, 不需要真值 SOC 曲线, 但随 OCV 表变化。
 *   重标 OCV 表之后这个散布会变小, 建议用 PC 脚本重新估一遍。 */
#define SOH_Q_SIG_K            126.0f   /* sigma_Q(%) = 本值 / ΔSOC(%); 30% -> 4.2% */
#define SOH_Q_KF_P0            0.02f    /* Q 初值相对不确定度 (标称可信到 ±2%) */
#define SOH_Q_KF_Q             0.002f   /* 过程噪声: 两次测量间容量可能的漂移 (相对值)。
                                         * 调大 -> 允许容量学得更"活" (也更抖);
                                         * 调小 -> 容量更稳, 但老化跟得慢 */
#define SOH_Q_KF_RUP           8.0f     /* 正向新息的量测噪声放大倍数 (抑制 SOH 上跳)。
                                         * 调大 -> SOH 更难上升 (防虚高);
                                         * 调小 -> 上升更灵敏 (也可能被噪声抬上去) */

