/* =====================================================================
 * [2] 调度与时基
 * ===================================================================== */

/* 主循环调用 SOC_AhUpdate() / SOH_Update() 的名义间隔 (ms)。
 *
 * 改成别的周期时, 本文件里这些"按帧数"定义的参数要一起换算:
 *   SOC_QUIET_DEBOUNCE / SOH_IDLE_DEBOUNCE  ≈ 1000 / 周期  (约 1s 消抖)
 *   SOH_R0_TAIL_N                           ≈ 1000 / 周期  (约 1s 的末段均值)
 * EKF 的步长 dt 直接取本宏换算, 自动跟随, 不需要另改。
 * 安时积分用的是真实时间戳差 (BMS_NowMs), 与本宏无关 —— 本宏只决定
 * "拿不到时间戳时的兜底 dt" 和 "EKF 的标称步长"。 */
#define BMS_UPDATE_PERIOD_MS       200

/* 单帧时间戳跳变保护: 相邻两帧的时间戳差超过本值, 视为异常帧
 * (复位 / 长时间阻塞 / 调试断点), 积分与计时用 BMS_UPDATE_PERIOD_MS 兜底。
 * 设得比正常帧间隔大一个量级以上即可; 太小会误判正常的偶发丢帧。 */
#define BMS_DT_MAX_MS              2000

/* =====================================================================
 * [3] 静置判据 —— "什么时候算静置" + "静置多久才动作"
 *
 * 这里有两条独立的时间线, 服务两个不同目的, 不要混:
 *   SOC_IDLE_MS      静置满 15min -> 用 OCV 查表校正安时积分基准 (纠漂移)
 *   SOH_MIN_REST_MS  静置满 10min -> 记一个 OCV 锚点, 攒够跨度学容量
 * 两者都要求极化电压基本消掉读数才准, 而极化时间常数 τ 见 SOC_TAU_TABLE_S
 * (平台区最大 125s), 所以经验关系是:
 *   SOC_IDLE_MS      ≈ 6~8 倍 τ_max   (900s / 125s = 7.2)
 *   SOH_MIN_REST_MS  ≈ 4~5 倍 τ_max   (600s / 125s = 4.8)
 * 换电芯后若 τ 表变化明显, 按同样的倍数关系重新取这两个值。
 * 取小了: OCV 读数还带极化, 会把 SOC 基准/容量学歪 (系统性误差)。
 * 取大了: 只是变慢, 不会算错。
 * ===================================================================== */

/* 静置电流门限 (mA): |I| 小于本值视为"静置"。
 * 取值依据: 参考板上用的电流采样芯片在静置时实测噪声约 ±19mA, 20mA 卡在
 * 噪声上沿。换成噪声更大 (或更小) 的电流计必须按实测噪声重取本值 ——
 * 取小了静置检测永远不通过, 取大了小电流工况会被误判成静置。 */
#define SOC_IDLE_CUR_MA        20       /* soc.c 用 */
#define SOH_IDLE_MA            20       /* soh.c 用 (两者保持同值) */

/* 静置消抖帧数: 连续 N 帧 |I| 低于门限才算真的进入静置态 (~N × 周期)。
 * 目的: (a) 挡住单帧电流毛刺重置静置计时器;
 *       (b) 静置态下本帧跳过安时积分, 堵住上述电流噪声被当小电流累计的漂移。
 * 必须 >= 1 帧; 5 帧 = 1s, 与人工"电流稳定 1 秒以上"的经验一致。 */
#define SOC_QUIET_DEBOUNCE     5        /* soc.c: ~1s */
#define SOH_IDLE_DEBOUNCE      5        /* soh.c: ~1s (两者保持同值) */

/* SOC: OCV 重同步所需的连续静置时长 (ms), 900000u = 900s = 15min。
 * 达到后向 OCV 查表值平滑校正积分基准 (首次直接覆盖, 之后半衰收敛)。 */
#define SOC_IDLE_MS            900000u

/* SOC: 每次重同步最多修正多少 (0.01% 单位, 200 = 2%)。
 * 只对"非首次"重同步生效 (首次是直接覆盖)。调大 -> 收敛快但显示会跳数字;
 * 调小 -> 显示平滑但大偏差要多次静置才逼近。 */
#define SOC_RESYNC_MAX_01      200

/* SOH: 记一个 OCV 锚点所需的连续静置时长 (ms), 600000u = 600s = 10min。
 * 这个锚点只负责"记下当时的 SOC 与已放出电荷", 真正学容量要等两个锚点
 * 之间的跨度同时满足 SOH_Q_MIN_DSOC_01 与 SOH_Q_MIN_DQ_MAH。 */
#define SOH_MIN_REST_MS        600000u

/* =====================================================================
 * [4] EKF 参数 —— 一阶 RC 扩展卡尔曼 (端压平滑 + 极化观测 + SOC 微修)
 *
 * 状态 x = [soc(%), vrc(mV)]; 量测 = 端压
 *   soc' = soc - I*dt/(cap*3600)*100          (放电为正)
 *   vrc' = a*vrc + I*R1/1000*(1-a), a = exp(-dt/tau)
 *   h    = OCV(soc) - I*R0/1000 - vrc
 *
 * 全量调参结果 (49072 帧实测): q_soc=1e-3, q_vrc=0.5, R=10
 *   带载段 99.98% 单调下降, 各静置末与安时积分参考 RMS 偏差 0.72%
 *
 * 怎么改 (调一个, 另一个不动):
 *   Q 调小 = 更信积分/模型 -> 显示更平滑, 但对真实 SOC 变化的响应变慢
 *   Q 调大 = 更信当前数据 -> 响应快, 代价是电流噪声会传到 SOC 上
 *   R 调大 = 更信模型 -> 端压预测偏了也不怎么改 SOC (抗野值, 但跟不紧)
 *   R 调小 = 更信量测 -> SOC 跟端压跟得紧, 电流/电压噪声也更明显地传进来
 * 一般只在"电流采样噪声明显不同"的场景才动 R。
 * 换电芯体系 (LFP / 钠电, 电压平台极平) 时 Q/R 需要重新扫参。
 * ===================================================================== */

/* 过程噪声: 每帧 SOC 变化的不确定度 (%^2/帧) */
#define BMS_EKF_Q_SOC          0.001f
